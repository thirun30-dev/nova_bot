// Copy the static export (out/) into the ROS package's web/ folder, which CMake installs
// and nova_dashboard.py serves. Run via `npm run build`.
import { cpSync, existsSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "out");
const web = join(here, "..", "..", "web");
if (!existsSync(join(out, "index.html"))) {
  console.error("export.mjs: out/index.html missing, did `next build` succeed?");
  process.exit(1);
}
rmSync(web, { recursive: true, force: true });
cpSync(out, web, { recursive: true });
writeFileSync(join(web, "README.md"),
  "Generated by `npm run build` in ../webapp. Do not edit; change webapp/src instead.\n");
console.log(`export.mjs: copied ${out} -> ${web}`);
console.log("Next: cd ~/nova_ws && colcon build --symlink-install --packages-select nova_bot\n" +
  "      (installs the new files) and reload the page.");
